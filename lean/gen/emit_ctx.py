"""Write QuadricDegree/Q8PlusContexts.lean: the 1575 contexts of Q+(7,2) as literal chunks of R rows,
each chunk checked against `contexts 0` by its own `decide +kernel` (keeps kernel memory small)."""
import sys
R = 4
xb=lambda v,i:(v>>i)&1; zb=lambda v,i:(v>>(i+4))&1
def symp(u,v): return (sum(xb(u,i)&zb(v,i) for i in range(4))+sum(zb(u,i)&xb(v,i) for i in range(4)))%2
def Q(v): return sum(xb(v,i)&zb(v,i) for i in range(4))%2
qp=lambda v: 0<v<256 and Q(v)==0
ctx=[(a,b) for a in range(256) for b in range(256) if a<b<(a^b) and qp(a) and qp(b) and qp(a^b) and symp(a,b)==0]
assert len(ctx)==1575
N=256//R
def wrap(items, indent="    ", width=98):
    lines, line = [], indent
    for it in items:
        t = it + ", "
        if len(line) + len(t) > width:
            lines.append(line.rstrip()); line = indent
        line += t
    lines.append(line.rstrip().rstrip(","))
    return "\n".join(lines)
L=["/-\nReleased under the MIT license (see LICENSE).\n-/\nimport QuadricDegree.Basic\n",
"""/-!
# The contexts of `Q⁺(7,2)` as a literal list

Generated by `gen/emit_ctx.py`. Evaluating `contexts 0` (a filter over `256²` pairs) in one
kernel computation needs several gigabytes, because the kernel caches every intermediate term. Here
the rows `a` are cut into %d chunks of %d; each chunk is compared with a literal list by its own
`decide +kernel`, and `contexts_eq` assembles them: `contexts 0 = ctxLit`. Later kernel checks use
the literal `ctxLit` instead of recomputing `contexts 0`.
-/
""" % (N,R),
"namespace Contextuality.Pauli.Q8Plus\n",
"/-- The contexts `(a, b)` of `Q_0` with first point `a`. -/\ndef ctxRow (a : ℕ) : List (ℕ × ℕ) :=\n  ((List.range 256).map fun b => (a, b)).filter (IsContext 0 ·)\n",
"lemma contexts_zero_eq : contexts 0 = (List.range 256).flatMap ctxRow := rfl\n"]
for c in range(N):
    ch=[t for t in ctx if R*c <= t[0] < R*c+R]
    parts=[]; line="  "
    for t in ch:
        s1="(%d,%d),"%t
        if len(line)+len(s1)>98: parts.append(line); line="  "
        line+=s1
    parts.append(line)
    lit="\n".join(parts).rstrip(",")
    L.append("/-- Contexts with first point in `[%d, %d)`. -/\ndef ctxChunk%d : List (ℕ × ℕ) := [\n%s]\n" % (R*c,R*c+R,c,lit if ch else ""))
L.append("/-- The chunks of contexts. -/\ndef ctxChunks : List (List (ℕ × ℕ)) := [\n  " + ",\n  ".join("ctxChunk%d"%c for c in range(N)) + "]\n")
L.append("/-- The contexts with first point in `[%d c, %d c + %d)`, as a literal list. -/\ndef cchunk (c : ℕ) : List (ℕ × ℕ) := ctxChunks.getD c []\n" % (R,R,R))
L.append("/-- The chunk `c` of `contexts 0` equals the literal chunk `cchunk c`. -/\ndef ctxOK (c : ℕ) : Bool := decide ((List.range' (%d * c) %d).flatMap ctxRow = cchunk c)\n" % (R,R))
for c in range(N):
    L.append("theorem ctxOK_%d : ctxOK %d = true := by decide +kernel" % (c,c))
L.append("")
L.append("theorem ctxOK_all : ∀ c ∈ List.range %d, ctxOK c = true := by\n  rw [show List.range %d = [\n%s]\n    by decide +kernel]\n  simp only [List.mem_cons, List.not_mem_nil, or_false, forall_eq_or_imp, forall_eq]\n  exact ⟨\n%s⟩\n" % (N,N,wrap([str(c) for c in range(N)]), wrap(["ctxOK_%d"%c for c in range(N)])))
L.append("""lemma range_256_eq : List.range 256 = (List.range %d).flatMap fun c => List.range' (%d * c) %d := by
  decide +kernel

/-- The contexts of `Q_0`, as the concatenation of the literal chunks. -/
theorem contexts_eq : contexts 0 = (List.range %d).flatMap cchunk := by
  rw [contexts_zero_eq, range_256_eq, List.flatMap_assoc]
  refine List.flatMap_congr fun c hc => ?_
  exact of_decide_eq_true (ctxOK_all c hc)
""" % (N,R,R,N))
L.append("end Contextuality.Pauli.Q8Plus\n")
open(sys.argv[1],'w').write("\n".join(L))
