from pathlib import Path as _Path
_CODE = str(_Path(__file__).resolve().parents[2] / 'code')  # the repository's code/ folder
import json, sys
d=json.load(open(sys.argv[1])); D=d['doilies']; G=d['grids']; mult=int(sys.argv[2]); out=sys.argv[3]
sys.path.insert(0,_CODE)
u=json.load(open(_CODE + '/witness.json'))
enc=lambda p: sum(p[i]<<i for i in range(8))
W=sum(1<<enc(p) for p,xv in zip(u['points'],u['assignment']) if xv)
packed=[sum(k<<(16*j) for j,k in enumerate(r)) for r in D]
rounds=(len(D)-1).bit_length()
L=[]
L.append("/-\nReleased under the MIT license (see LICENSE).\n-/\nimport Mathlib.Init\n")
L.append("/-!\n# Data for the contextuality degree of the hyperbolic quadric `Q⁺(7,2)`\n\nGenerated by a Python script. Nothing here is trusted: every property used is checked by the kernel\nin `QuadricDegree/Q8Plus.lean`.\n\n* `doilyData`: %d doilies (parabolic sections `Q(4,2)`, generalised quadrangles `GQ(2,2)`) of the\n  quadric, each packed as `15` context keys `256 a + b` of `16` bits each, the contexts listed in\n  the order of a fixed labelling of `GQ(2,2)`.\n* `gridPos`: the `10` grids of `GQ(2,2)`, as positions in that labelling.\n* `bucketData i`: the keys of the doilies of chunk `i`, sorted and split by `key / 1024`.\n* `witness`: an assignment, as the bit mask of the points with value `1` (outcome `-1`).\n-/\n" % len(D))
L.append("namespace Contextuality.Pauli.Q8Plus\n")
L.append("/-- Number of doilies. -/\ndef numDoilies : Nat := %d\n" % len(D))
L.append("/-- Number of doilies through each context. -/\ndef mult : Nat := %d\n" % mult)
L.append("/-- Rounds of pairwise merging needed to merge `numDoilies` lists. -/\ndef rounds : Nat := %d\n" % rounds)
L.append("/-- The grids of `GQ(2,2)` as sets of line positions. -/\ndef gridPos : List (List Nat) := %s\n" % ",\n    ".join(json.dumps(g).replace(' ','') for g in G).join(["[", "]"]))
L.append("/-- An assignment violating `315` contexts. -/\ndef witness : Nat :=\n  %d\n" % W)
CH=100
chunks=[packed[i:i+CH] for i in range(0,len(packed),CH)]
for ci,ch in enumerate(chunks):
    L.append("/-- Doilies, packed (part %d). -/\ndef doilyData%d : List Nat := [\n" % (ci,ci) + ",\n".join("  %d" % n for n in ch) + "]\n")
L.append("/-- Number of chunks of doilies. -/\ndef numChunks : Nat := %d\n" % len(chunks))
L.append("/-- The chunks of doilies, packed. -/\ndef doilyChunks : List (List Nat) := [\n  " + ",\n  ".join("doilyData%d" % ci for ci in range(len(chunks))) + "]\n")
# buckets: for chunk i and context chunk c (keys k with k / 1024 = c, i.e. first point in [4c, 4c+4)),
# the sorted keys of the doilies of chunk i in that range
NB=64
def wrapl(b, width=98):
    """A list literal, indented by 2, wrapped to `width` columns."""
    lines, line = [], "  ["
    for k in b:
        t = str(k) + ","
        if len(line) + len(t) > width:
            lines.append(line); line = "   "
        line += t
    return "\n".join(lines + [line.rstrip(",") + "]"])
for ci,ch in enumerate(chunks):
    keys=[k for r in D[ci*CH:(ci+1)*CH] for k in r]
    B=[sorted(k for k in keys if k//1024==c) for c in range(NB)]
    assert sum(len(b) for b in B)==len(keys)
    L.append("/-- The keys of the doilies of chunk %d, sorted and split by `key / 1024`. -/\ndef bucketData%d : List (List Nat) := [\n" % (ci,ci) + ",\n".join(wrapl(b) for b in B) + "]\n")
L.append("/-- The sorted keys of all chunks. -/\ndef buckets : List (List (List Nat)) := [\n  " + ",\n  ".join("bucketData%d" % ci for ci in range(len(chunks))) + "]\n")
L.append("end Contextuality.Pauli.Q8Plus\n")
open(out,'w').write("\n".join(L))
