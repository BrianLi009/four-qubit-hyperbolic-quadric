"""Write QuadricDegree/Q8PlusChecks.lean: the kernel checks on the doily data, one `decide +kernel`
theorem per chunk (each stays well under 1 GB of kernel memory), combined into `∀` statements."""
import sys
NCH, NB = 26, 64

def wrap(items, indent="  ", width=98):
    lines, line = [], indent
    for it in items:
        s = it + ", "
        if len(line) + len(s) > width:
            lines.append(line.rstrip()); line = indent
        line += s
    lines.append(line.rstrip().rstrip(","))
    return "\n".join(lines)

def combine(name, pred, n, bound):
    nums = wrap([str(c) for c in range(n)], "    ")
    pfs = wrap(["%s_%d" % (pred, c) for c in range(n)], "    ")
    return ("theorem %s : ∀ c ∈ List.range %s, %s c = true := by\n"
            "  rw [show List.range %s = [\n%s]\n    by decide +kernel]\n"
            "  simp only [List.mem_cons, List.not_mem_nil, or_false, forall_eq_or_imp, forall_eq]\n"
            "  exact ⟨\n%s⟩\n" % (name, bound, pred, bound, nums, pfs))

L = ["""/-
Released under the GNU GPLv3 license.
-/
import QuadricDegree.OddSets
import QuadricDegree.Q8PlusData
import QuadricDegree.Q8PlusContexts

/-!
# Kernel checks on the doilies of `Q⁺(7,2)`

Generated by `gen/emit_checks.py`. Every check is a `decide +kernel` over one chunk of the
data, so that no single kernel computation gets large (the kernel caches every intermediate term,
so one computation over all `2520` doilies needs more than `10` GB).

* `sortOK i`: the keys of the doilies of chunk `i`, merge-sorted, are the keys of `bucketData i`,
  read bucket by bucket.
* `bucketOK c`: the keys of bucket `c` of all chunks, merged, are the contexts of `cchunk c`, each
  repeated `mult` times.
* `gridChk i`: in every doily of chunk `i`, each of the `10` grids is an odd set.

Together (`QuadricDegree/Q8Plus.lean`) they show that the keys of all doilies are a permutation of the
contexts, each repeated `mult` times.
-/

namespace Contextuality.Pauli.Q8Plus

/-- The context with key `256 a + b`. -/
def ofKey (k : ℕ) : ℕ × ℕ := (k / 256, k % 256)

/-- The key of a context. -/
def keyOf (t : ℕ × ℕ) : ℕ := t.1 * 256 + t.2

/-- The `15` keys packed in a natural number, `16` bits each. -/
def unpack (n : ℕ) : List ℕ := (List.range 15).map fun j => n / 65536 ^ j % 65536

/-- The packed doilies of chunk `i`. -/
def dchunk (i : ℕ) : List ℕ := doilyChunks.getD i []

/-- The sorted keys of chunk `i` in bucket `c`. -/
def bucket (i c : ℕ) : List ℕ := (buckets.getD i []).getD c []

/-- The keys of the doilies of chunk `i`. -/
def chunkKeys (i : ℕ) : List ℕ := ((dchunk i).map unpack).flatten

/-- The keys of chunk `i`, merge-sorted, are its buckets. -/
def sortOK (i : ℕ) : Bool :=
  decide (mergeTree 11 ((chunkKeys i).map fun k => [k]) = (List.range @NB@).flatMap (bucket i))

/-- The key of a context, `mult` times. -/
def rep (t : ℕ × ℕ) : List ℕ := List.replicate mult (keyOf t)

/-- Bucket `c` of all chunks, merged, is every context of `cchunk c`, `mult` times. -/
def bucketOK (c : ℕ) : Bool :=
  decide (mergeTree 5 ((List.range numChunks).map fun i => bucket i c) = (cchunk c).flatMap rep)

/-- The grid with positions `G` of the doily `D` is an odd set. -/
def gridOK (D G : List ℕ) : Bool :=
  let S := G.map fun j => ofKey (D.getD j 0)
  xmask S == 0 && parity (S.map fun t => negB t.1 t.2)

/-- All grids of all doilies of chunk `i` are odd sets. -/
def gridChk (i : ℕ) : Bool := ((dchunk i).map unpack).all fun D => gridPos.all (gridOK D)
""".replace("@NB@", str(NB))]
L.append("lemma numChunks_eq : numChunks = %d := rfl\n" % NCH)
for i in range(NCH):
    L.append("theorem sortOK_%d : sortOK %d = true := by decide +kernel" % (i, i))
L.append("")
for i in range(NCH):
    L.append("theorem gridChk_%d : gridChk %d = true := by decide +kernel" % (i, i))
L.append("")
for c in range(NB):
    L.append("theorem bucketOK_%d : bucketOK %d = true := by decide +kernel" % (c, c))
L.append("")
L.append(combine("sortOK_all", "sortOK", NCH, "numChunks"))
L.append(combine("gridChk_all", "gridChk", NCH, "numChunks"))
L.append(combine("bucketOK_all", "bucketOK", NB, str(NB)))
L.append("end Contextuality.Pauli.Q8Plus\n")
open(sys.argv[1], "w").write("\n".join(L))
